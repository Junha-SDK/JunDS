// ─── (c) TS (react 어댑터 호환 표면) ───────────────────────────────────────

const tsKey = (k) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k) || /^\d+(\.\d+)?$/.test(k) ? k : JSON.stringify(k));
const tsStr = (v) => JSON.stringify(String(v));

function tsObject(entries, indent = "  ") {
  return "{\n" + entries.map(([k, v]) => `${indent}${tsKey(k)}: ${v},`).join("\n") + `\n${indent.slice(2)}}`;
}

export async function buildTs(tokens) {
  const { reactColorsShape, priorityLabels } = await import("./legacy-map.mjs");

  const colorVar = (key) => {
    const leaf = collectLeaves("color", tokens.color).find((l) => l.path.join(".") === key);
    if (!leaf) throw new GenError(`reactColorsShape: color.${key} 없음`);
    return `"var(${cssVarName("color", leaf.path)})"`;
  };
  const colorGroups = Object.entries(reactColorsShape).map(([group, shape]) => {
    const inner = Object.entries(shape).map(([prop, key]) => [prop, colorVar(key)]);
    return [group, tsObject(inner, "    ")];
  });

  /* status·priority는 DEC-044에서 모드 인식 토큰이 됐다 — 리터럴 hex를 그대로
     내보내면 React 표면만 라이트에 굳는다. 변수 참조로 방출해 런타임에 테마를 따른다
     (colors 그룹이 이미 쓰는 방식과 동일). 키·모양은 v2 그대로. */
  const groupVar = (group, key, prop) =>
    tsStr(`var(${cssVarName("color", [group, key, prop])})`);

  const priority = Object.entries(tokens.color.priority).filter(([k]) => !k.startsWith("$"))
    .map(([k, _v], i) => [String(i), tsObject([
      ["label", tsStr(priorityLabels[i])],
      ["bg", groupVar("priority", k, "bg")],
      ["text", groupVar("priority", k, "text")],
      ["border", groupVar("priority", k, "border")],
    ], "    ")]);

  const status = Object.entries(tokens.color.status).filter(([k]) => !k.startsWith("$"))
    .map(([k]) => [k, tsObject([
      ["bg", groupVar("status", k, "bg")],
      ["text", groupVar("status", k, "text")],
    ], "    ")]);

  const flat = (tree, mapVal = (v) => tsStr(v)) =>
    Object.entries(tree).filter(([k]) => !k.startsWith("$")).map(([k, v]) => [k, mapVal(v)]);

  const shadowsEntries = collectLeaves("shadow", tokens.shadow).map((l) => {
    // v2 shadows.ts API 키 유지: focusRing→glow, focusRingDanger→danger (역개명)
    const v2Key = { focusRing: "glow", focusRingDanger: "danger" }[l.path[0]] ?? l.path[0];
    return [v2Key, tsStr(aliasToVar(tokens, l.light))];
  });

  const gradients = flat(tokens.gradient, (v) => tsStr(aliasToVar(tokens, v)));
  const breakpoints = flat(tokens.breakpoint, (v) => num(v));
  const mediaQueries = flat(tokens.breakpoint, (v) => tsStr(`(min-width: ${v}px)`));

  return `/* ${BANNER} */
/* 기존 ds/tokens 배럴과 API 호환 — var() 참조는 v3 변수명(--jd-*)을 가리킨다 (02-tokens §4.3).
   themes/brands 함수류(applyTheme 등)와 animationClass는 생성 대상이 아니라 런타임 코드 (§4.4·§4.5). */

export const colors = ${tsObject(colorGroups)} as const;

export const priorityColors = ${tsObject(priority)} as const;

export const statusColors = ${tsObject(status)} as const;

export const spacing = ${tsObject(flat(tokens.space))} as const;

export const fontSize = ${tsObject(flat(tokens.type.fontSize))} as const;

export const fontWeight = ${tsObject(flat(tokens.type.fontWeight))} as const;

export const lineHeight = ${tsObject(flat(tokens.type.lineHeight))} as const;

export const letterSpacing = ${tsObject(flat(tokens.type.letterSpacing))} as const;

export const fontFamily = ${tsObject(flat(tokens.type.fontFamily))} as const;

export const shadows = ${tsObject(shadowsEntries)} as const;

export const radius = ${tsObject(flat(tokens.radius))} as const;

export const duration = ${tsObject(flat(tokens.motion.duration))} as const;

export const easing = ${tsObject(flat(tokens.motion.easing))} as const;

export const zIndex = ${tsObject(flat(tokens.zindex, (v) => num(v)))} as const;

export const opacity = ${tsObject(flat(tokens.opacity))} as const;
export type OpacityScale = keyof typeof opacity;

export const borderWidth = ${tsObject(flat(tokens.border))} as const;
export type BorderWidthScale = keyof typeof borderWidth;

export const breakpoints = ${tsObject(breakpoints)} as const;
export type Breakpoint = keyof typeof breakpoints;

export const mediaQueries: Record<Breakpoint, string> = ${tsObject(mediaQueries)};

export const gradients = ${tsObject(gradients)} as const;
export type GradientPreset = keyof typeof gradients;
`;
}

// ─── main ──────────────────────────────────────────────────────────────────

export async function generate() {
  const tokens = loadTokens();
  const css = buildCss(tokens);
  const swift = buildSwift(tokens);
  const ts = await buildTs(tokens);
  for (const [out, text] of [[OUT_CSS, css], [OUT_SWIFT, swift], [OUT_TS, ts]]) {
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, text);
  }
  const count = CSS_CATEGORIES.reduce((n, c) => n + collectLeaves(c, tokens[c]).length, 0);
  console.log(`[tokens] ${count}개 토큰 → 3산출물 생성 완료`);
  console.log(`  css   : ${OUT_CSS}`);
  console.log(`  swift : ${OUT_SWIFT}`);
  console.log(`  ts    : ${OUT_TS}`);
}

const isMain = process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url;
if (isMain) {
  generate().catch((e) => {
    console.error(`[tokens] 생성 실패: ${e.message}`);
    process.exit(1);
  });
}
