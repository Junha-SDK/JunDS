/**
 * gen-manifest — 라이브러리가 도구에게 자기를 설명하는 세 산출물 (DEC-044).
 *
 * 지금까지 JunDS 의 표면은 **사람이 읽는 문서**에만 있었다. 그래서 소비자가
 * `<jd-alert ` 까지 치면 편집기는 아무것도 모른다 — 어떤 속성이 있는지, 값이
 * 무엇인지, 무슨 이벤트가 나가는지. 커스텀 엘리먼트 생태계에는 이걸 위한 표준
 * 형식이 이미 있고, 우리는 그 정보를 전부 갖고 있었는데 내보내지 않고 있었다.
 *
 *  1. custom-elements.json (CEM 2.1.0)
 *     — 커스텀 엘리먼트 매니페스트 표준. Storybook·Web Types·문서 생성기·
 *       각종 에디터 플러그인이 공통으로 읽는다. package.json 의 "customElements"
 *       필드가 이 파일을 가리키면 도구들이 알아서 찾아간다.
 *  2. vscode.html-custom-data.json
 *     — VS Code 의 HTML 자동완성 데이터. 소비자가 설정에 이 파일을 추가하면
 *       태그·속성·허용 값이 그대로 자동완성되고 설명이 툴팁으로 뜬다.
 *  3. src/elements.generated.ts
 *     — HTMLElementTagNameMap 증강. 바닐라 TS 소비자의
 *       `document.querySelector("jd-alert")` 가 HTMLElement 가 아니라 JdAlert 로
 *       좁혀진다. React 어댑터를 쓰지 않는 쪽에는 이게 유일한 타입 통로였다.
 *
 * 값 목록(허용 값)이 특히 중요하다 — `variant="danger"` 처럼 CSS 셀렉터에만
 * 적혀 있던 것이 여기 실리면 편집기가 값까지 제안한다.
 *
 * 실행:  node packages/web/scripts/gen-manifest.mjs [--check]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { collectSurface } from "./lib/surface.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const webDir = join(here, "..");
const OUT_CEM = join(webDir, "custom-elements.json");
const OUT_VSCODE = join(webDir, "vscode.html-custom-data.json");
const OUT_TS = join(webDir, "src/elements.generated.ts");

const surface = await collectSurface();

/** CEM 의 type.text — 열거값이 있으면 유니언으로 낸다(편집기가 값을 제안한다) */
const typeText = (p) => {
  if (p.kind === "data") return "unknown";
  if (p.options?.length) return p.options.map((o) => JSON.stringify(o)).join(" | ");
  return p.kind;
};
const defaultText = (p) =>
  p.default === undefined ? undefined : JSON.stringify(p.default);

/* ── 1. custom-elements.json ─────────────────────────────────────────── */
const modules = surface.map((c) => {
  const path = `dist/components/${c.dir}/index.js`;
  const members = c.props.map((p) => ({
    kind: "field",
    name: p.name,
    privacy: "public",
    ...(p.description ? { description: p.description } : {}),
    type: { text: typeText(p) },
    ...(defaultText(p) !== undefined ? { default: defaultText(p) } : {}),
    ...(p.attribute ? { attribute: p.attribute } : {}),
    ...(p.reflects ? { reflects: true } : {}),
  }));
  const attributes = c.props
    .filter((p) => p.attribute)
    .map((p) => ({
      name: p.attribute,
      ...(p.description ? { description: p.description } : {}),
      type: { text: typeText(p) },
      ...(defaultText(p) !== undefined ? { default: defaultText(p) } : {}),
      fieldName: p.name,
    }));
  return {
    kind: "javascript-module",
    path,
    declarations: [
      {
        kind: "class",
        ...(c.description ? { description: c.description } : {}),
        name: c.className,
        tagName: c.tag,
        customElement: true,
        superclass: { name: "JdElement", module: "dist/core/element.js" },
        ...(members.length ? { members } : {}),
        ...(attributes.length ? { attributes } : {}),
        ...(c.events.length
          ? { events: c.events.map((e) => ({ name: e, type: { text: "CustomEvent" } })) }
          : {}),
      },
    ],
    exports: [
      {
        kind: "js",
        name: c.className,
        declaration: { name: c.className, module: path },
      },
      {
        kind: "custom-element-definition",
        name: c.tag,
        declaration: { name: c.className, module: path },
      },
    ],
  };
});

const cem = {
  schemaVersion: "2.1.0",
  readme: "packages/web/README.md",
  modules,
};

/* ── 2. VS Code HTML custom data ─────────────────────────────────────── */
const vscode = {
  version: 1.1,
  tags: surface.map((c) => ({
    name: c.tag,
    ...(c.description ? { description: c.description } : {}),
    attributes: c.props
      .filter((p) => p.attribute)
      .map((p) => ({
        name: p.attribute,
        ...(p.description ? { description: p.description } : {}),
        ...(p.options?.length ? { values: p.options.map((v) => ({ name: v })) } : {}),
        ...(p.kind === "boolean" ? { valueSet: "v" } : {}),
      })),
    references: [
      { name: "JunDS 문서", url: `https://junha.dev/docs/projects/junds?c=${c.dir}` },
    ],
  })),
};

/* ── 3. HTMLElementTagNameMap 증강 ───────────────────────────────────── */
const imports = [...new Set(surface.map((c) => c.dir))]
  .sort()
  .map((dir) => {
    const classes = surface.filter((c) => c.dir === dir).map((c) => c.className);
    return `import type { ${[...new Set(classes)].join(", ")} } from "./components/${dir}/element.js";`;
  });
const entries = surface.map((c) => `    ${JSON.stringify(c.tag)}: ${c.className};`);

const tsSource = [
  "/* AUTO-GENERATED by scripts/gen-manifest.mjs — DO NOT EDIT (DEC-044) */",
  "",
  "/**",
  " * HTMLElementTagNameMap 증강 — 바닐라 TS 소비자를 위한 타입 통로.",
  " *",
  " * 이 모듈을 한 번 import 하면(부작용 없는 타입 전용) 아래가 전부 좁혀진다:",
  ' *   document.querySelector("jd-alert")   → JdAlert | null',
  ' *   document.createElement("jd-alert")   → JdAlert',
  " *",
  " * React 어댑터를 쓰지 않는 쪽에는 이것이 유일한 타입 통로였다.",
  " */",
  ...imports,
  "",
  "declare global {",
  "  interface HTMLElementTagNameMap {",
  ...entries,
  "  }",
  "}",
  "",
  "export {};",
  "",
].join("\n");

/* ── 쓰기 / 검사 ─────────────────────────────────────────────────────── */
const files = [
  [OUT_CEM, JSON.stringify(cem, null, 2) + "\n"],
  [OUT_VSCODE, JSON.stringify(vscode, null, 2) + "\n"],
  [OUT_TS, tsSource],
];
const read = (p) => {
  try {
    return readFileSync(p, "utf8");
  } catch {
    return null;
  }
};

if (process.argv.includes("--check")) {
  const stale = files.filter(([p, text]) => read(p) !== text).map(([p]) => p);
  if (stale.length) {
    console.error(
      `✗ gen-manifest drift: ${stale.map((p) => p.split("/").pop()).join(", ")} — ` +
        "node scripts/gen-manifest.mjs 재실행 필요",
    );
    process.exit(1);
  }
  console.log(`✓ gen-manifest drift 없음 (${surface.length}종)`);
} else {
  for (const [p, text] of files) writeFileSync(p, text);
  const withOptions = surface.reduce(
    (n, c) => n + c.props.filter((p) => p.options?.length).length,
    0,
  );
  console.log(
    `✓ custom-elements.json · vscode.html-custom-data.json · elements.generated.ts` +
      ` — ${surface.length}종 · 값 목록 ${withOptions}개 프롭`,
  );
}
